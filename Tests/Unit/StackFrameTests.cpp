void compare(const std::vector<int> &got, const std::vector<int> &expected, const HardwareTest &t, const char *cpu)
{
    REQUIRE(got.size() == expected.size());

    for (size_t i = 0; i < expected.size(); i++) {

        if (expected[i] < 0) continue;

        INFO(t.name, " (", cpu, "): ", t.instruction, ", word ", i);
        CHECK(got[i] == expected[i]);
    }
}

