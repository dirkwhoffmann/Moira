/* Exception stack frames, compared with the frames recorded on real Amigas (68000 and 68010). The tests
 * are taken from the vAmigaTS test suite (CPU/Exceptions/StackFrame/addrerr1 ... addrerr31). Each of them
 * runs a short program that moves the stack to a fixed location, clears the stack, executes one instruction
 * that causes an exception, and records the 22 words shown on the screen: the stack pointer, the size of the
 * frame, the frame itself (7 words on the 68000, 13 words on the 68010) and the address registers A4 and A5.
 * The program is replayed here, including the stack clearing, because the frame contains stale data (the
 * unused words and the data buffers). Words that depend on the recorded machine are marked with -1. This
 * applies to the registers A4 and A5 if the test does not set them, to the word at address $200 (it is
 * $00FC on the recorded machines) and to the bus-dependent DIB in addrerr6.
 */
class AmigaCPU : public Moira {

public:

    mutable std::vector<u8> ram = std::vector<u8>(1 << 20);

    static constexpr u32 progStart = 0x757C0;   // Address of the "lea 0(pc),a6" instruction
    static constexpr u32 stackTop = 0x7FF00;
    static constexpr u32 clearStack = 0x60000;
    static constexpr u32 handler = 0x70000;

    u8 read8(u32 addr) const override { return ram[addr & 0xFFFFF]; }
    u16 read16(u32 addr) const override { return u16(ram[addr & 0xFFFFF] << 8 | ram[(addr + 1) & 0xFFFFF]); }
    u32 read32(u32 addr) const override { return u32(read16(addr)) << 16 | read16(addr + 2); }
    void write8(u32 addr, u8 val) const override { ram[addr & 0xFFFFF] = val; }
    void write16(u32 addr, u16 val) const override { ram[addr & 0xFFFFF] = u8(val >> 8); ram[(addr + 1) & 0xFFFFF] = u8(val); }
    void write32(u32 addr, u32 val) const override { write16(addr, u16(val >> 16)); write16(addr + 2, u16(val)); }

    void poke(u32 addr, std::initializer_list<u16> words) { for (u16 w : words) { write16(addr, w); addr += 2; } }
    void poke(u32 addr, const std::vector<u16> &words) { for (u16 w : words) { write16(addr, w); addr += 2; } }

    // Runs the test program and returns the recorded words (see above)
    std::vector<int> run(CPUModel model, const std::vector<u16> &code)
    {
        setModel(model);

        // clrstack: move.l a7,a2 / moveq #28,d2 / loop: move.w #$1111,-(a2) / dbra d2,loop / rts
        poke(clearStack, { 0x244F, 0x741C, 0x353C, 0x1111, 0x51CA, 0xFFFA, 0x4E75 });

        // jsr clrstack / move.l a7,a0 / lea 0(pc),a6
        poke(progStart - 8, { 0x4EB9, 0x0006, 0x0000, 0x204F, 0x4DFA, 0x0000 });

        // The instructions under test, followed by "move.w #$7FFF,DMACON(a1)" and friends
        u32 end = progStart + 4;
        poke(end, code);
        end += 2 * u32(code.size());
        poke(end, { 0x337C, 0x7FFF, 0x009A, 0x337C, 0x00F0, 0x0180, 0x60FE });

        // Address error and TRAP #1 vectors, and the handler
        write32(0x0C, handler);
        write32(0x84, handler);
        write16(0x200, 0x00FC);
        poke(handler, { 0x4AFC, 0x4AFC });

        reset();
        setSR(0x2010);
        setISP(stackTop);
        setPC(progStart - 8);
        setPC0(progStart - 8);
        setIRD(read16(progStart - 8));
        setIRC(read16(progStart - 6));

        for (int i = 0; i < 200 && getPC() != handler; i++) execute();
        REQUIRE(getPC() == handler);

        // Record the registers the way the test program does (the stack pointer is checked via the frame size)
        std::vector<int> rec = { int(getSP() >> 16), int(getSP() & 0xFFFF), int(stackTop - getSP()), 0, 0 };
        for (int i = 0; i < 13; i++) rec.push_back(model == CPUModel::M68000 && i >= 7 ? 0 : read16(getSP() + 2 * i));
        for (u32 a : { getA(4), getA(5) }) { rec.push_back(int(a >> 16)); rec.push_back(int(a & 0xFFFF)); }
        return rec;
    }
};

